def det3(M):
    return (M[0][0] * (M[1][1] * M[2][2] - M[1][2] * M[2][1])
            - M[0][1] * (M[1][0] * M[2][2] - M[1][2] * M[2][0])
            + M[0][2] * (M[1][0] * M[2][1] - M[1][1] * M[2][0]))


def inv3(M):
    d = det3(M)
    C = [[Fr(0)] * 3 for _ in range(3)]
    for i in range(3):
        for j in range(3):
            m = [[M[a][b] for b in range(3) if b != j] for a in range(3) if a != i]
            C[j][i] = Fr((-1) ** (i + j)) * (m[0][0] * m[1][1] - m[0][1] * m[1][0]) / d
    return C


def mul(A, B):
    return [[sum(A[i][k] * B[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def eye():
    return [[Fr(1) if i == j else Fr(0) for j in range(3)] for i in range(3)]


def bfs(adj, src):
    d = {src: 0}
    q = deque([src])
    while q:
        x = q.popleft()
        for y in adj[x]:
            if y not in d:
                d[y] = d[x] + 1
                q.append(y)
    return d


